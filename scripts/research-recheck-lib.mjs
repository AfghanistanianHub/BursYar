// Pure helpers for the research re-read assistant. Kept separate from the CLI so
// the date matching and the draft format can be tested without the network.
import {researchDeadlineOn} from '../src/research-catalog.js';

const MONTHS=['January','February','March','April','May','June','July','August','September','October','November','December'];

// A date argument is only accepted if it names a real calendar day: the regex
// alone would let `2026-13-01` or `2026-02-30` through and stamp a draft with a
// date that cannot exist.
export function isIsoDay(value){
 if(typeof value!=='string'||!/^\d{4}-\d{2}-\d{2}$/.test(value))return false;
 const parsed=new Date(`${value}T00:00:00.000Z`);
 return !Number.isNaN(parsed.getTime())&&parsed.toISOString().slice(0,10)===value;
}

// The assistant writes exactly one kind of file. Kept as a predicate so the
// refusal can be tested without a filesystem or a network, and applied by the
// CLI before anything is read or written.
export function isDraftPath(path){
 return typeof path==='string'&&/^docs\/RESEARCH-RECHECK-\d{4}-\d{2}-\d{2}\.md$/.test(path);
}

// A page can print a deadline many ways: "8 December 2026", "8th December 2026",
// "December 8, 2026", "08/12/2026" or "2026-12-08". All are accepted, both
// day/month orders included because an ambiguous numeric date must not be
// reported as missing. Nothing here infers a date that is not printed.
export function datePatterns(iso){
 const match=/^(\d{4})-(\d{2})-(\d{2})$/.exec(iso??'');
 if(!match)return [];
 const [,year,monthNumber,dayNumber]=match;
 const yearNumber=Number(year),month=Number(monthNumber),day=Number(dayNumber);
 if(month<1||month>12||day<1||day>31)return [];
 const monthName=MONTHS[month-1],short=monthName.slice(0,3);
 const dayText=String(day),padDay=String(day).padStart(2,'0'),padMonth=String(month).padStart(2,'0');
 const ordinal='(?:st|nd|rd|th)?';
 return [
  new RegExp(`\\b${dayText}${ordinal}\\s+${monthName}\\s*,?\\s*${yearNumber}\\b`,'i'),
  new RegExp(`\\b${monthName}\\s+${dayText}${ordinal}\\s*,?\\s*${yearNumber}\\b`,'i'),
  new RegExp(`\\b${dayText}${ordinal}\\s+${short}\\.?\\s*,?\\s*${yearNumber}\\b`,'i'),
  new RegExp(`\\b${short}\\.?\\s+${dayText}${ordinal}\\s*,?\\s*${yearNumber}\\b`,'i'),
  new RegExp(`\\b${padDay}[/.]${padMonth}[/.]${yearNumber}\\b`),
  new RegExp(`\\b${padMonth}[/.]${padDay}[/.]${yearNumber}\\b`),
  new RegExp(`\\b${yearNumber}-${padMonth}-${padDay}\\b`)
 ];
}

export function findDeadlineEvidence(text,iso){
 const patterns=datePatterns(iso);
 if(!patterns.length||typeof text!=='string')return {found:false,excerpt:''};
 for(const pattern of patterns){
  const hit=pattern.exec(text);
  if(!hit)continue;
  const start=Math.max(0,hit.index-120),end=Math.min(text.length,hit.index+hit[0].length+120);
  return {found:true,excerpt:text.slice(start,end).replace(/\s+/gu,' ').trim(),matched:hit[0]};
 }
 return {found:false,excerpt:''};
}

// `page` is {text, finalUrl} or {error}. Only three outcomes are possible, and
// none of them is an approval: a printed deadline found, a recorded deadline not
// found (a human must look), or a page that could not be read. A row with no
// recorded deadline gets reachability only, because absence of a date cannot be
// confirmed by a keyword search.
export function assessRow(row,page){
 if(!page||page.error)return {status:'unreachable',detail:page?.error??'no response'};
 const recorded=researchDeadlineOn(row);
 if(!recorded)return {status:'no_recorded_deadline',detail:page.finalUrl??'',evidence:''};
 const evidence=findDeadlineEvidence(page.text,recorded);
 if(evidence.found)return {status:'deadline_found',detail:evidence.matched,evidence:evidence.excerpt};
 return {status:'deadline_not_found',detail:`no printed ${recorded} in ${page.text.length} characters of extracted text`,evidence:''};
}

const LABELS={
 deadline_found:'Deadline still printed',
 deadline_not_found:'Recorded deadline not found',
 no_recorded_deadline:'No recorded deadline; page reachable',
 unreachable:'Page could not be read'
};

function cell(value){return String(value??'').replace(/\|/g,'\\|').replace(/\s+/gu,' ').trim()||'—';}

export function renderDraft({date, results, fetchedAt}){
 const rows=results.map(result=>`| \`${result.id}\` | ${cell(result.recordedDeadline)} | ${cell(result.evidence||result.detail)} | ${LABELS[result.status]} |`).join('\n');
 const needsWork=results.filter(result=>!['deadline_found','no_recorded_deadline'].includes(result.status));
 const found=results.filter(result=>result.status==='deadline_found').length;
 const none=results.filter(result=>result.status==='no_recorded_deadline').length;
 const unreachable=results.filter(result=>result.status==='unreachable').length;
 return `# Research source re-check — ${date} (DRAFT)

> Generated by \`npm run research:recheck\` on ${fetchedAt}. It records what each
> official page printed at fetch time and nothing else. **It is not evidence until
> a human signs it:** read the entries, decide what \`lastCheckedBy\` should say,
> update \`lastCheckedAt\` in \`src/research-data.js\` yourself, then rename this file
> so it is the dated record for that read. The assistant never writes a check date.

Scope: the ${results.length} public leads in \`src/research-data.js\` (BY-08). Each
\`sourceUrl\` was fetched on ${date}; the recorded deadline was compared with the
text the page served. A missing deadline is reported as missing, never inferred
from a neighbouring date or from an earlier year.

| ID | Catalog deadline | Evidence on the page | Verdict |
|---|---|---|---|
${rows}

## Result

- ${found} recorded deadline(s) found as printed.
- ${none} row(s) have no recorded deadline; reachability was the only check.
- ${unreachable} page(s) could not be read.
${needsWork.length?`- ${needsWork.length} row(s) need a human decision: ${needsWork.map(result=>`\`${result.id}\``).join(', ')}.`:'- No row needs a human decision beyond confirming the above.'}

## Provenance

\`lastCheckedAt\` and \`lastCheckedBy\` are unchanged by this run. A draft that is
committed without re-reading, or a date moved without a signed record, fails
\`tests/research-evidence.test.js\` and the freshness gate. fa/ps copy for these
strings stays UNREVIEWED pending a fluent reviewer (BY-21).
`;
}

export function draftPath(date){return `docs/RESEARCH-RECHECK-${date}.md`;}
